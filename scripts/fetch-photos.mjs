// Downloads every photo listed in content/photo-ids.json from Pexels, stores a
// 2000px WebP master in assets/photos, and writes content/images.ts with static
// imports so Next can size, blur and cache them at build time.
import { mkdir, writeFile, access } from "node:fs/promises";
import sharp from "sharp";
import ids from "../content/photo-ids.json" with { type: "json" };

const out = new URL("../assets/photos/", import.meta.url);
await mkdir(out, { recursive: true });

const all = [...new Set(Object.values(ids).flat())];

async function fetchOne(id) {
  const file = new URL(`${id}.webp`, out);
  try {
    await access(file);
    return;
  } catch {}
  const url = `https://images.pexels.com/photos/${id}/pexels-photo-${id}.jpeg?fm=jpg&w=2400`;
  const res = await fetch(url, { headers: { Accept: "image/jpeg" } });
  if (!res.ok) throw new Error(`${id}: ${res.status}`);
  const buf = Buffer.from(await res.arrayBuffer());
  await sharp(buf)
    .resize(2000, 2000, { fit: "inside", withoutEnlargement: true })
    .webp({ quality: 80, effort: 5 })
    .toFile(file.pathname);
  console.log("saved", id);
}

for (let i = 0; i < all.length; i += 6) {
  await Promise.all(all.slice(i, i + 6).map(fetchOne));
}

const lines = [
  "// Generated by scripts/fetch-photos.mjs. Do not edit by hand.",
  'import type { StaticImageData } from "next/image";',
  ...all.map((id) => `import p${id} from "@/assets/photos/${id}.webp";`),
  "",
  "export const images: Record<number, StaticImageData> = {",
  ...all.map((id) => `  ${id}: p${id},`),
  "};",
  "",
];
await writeFile(new URL("../content/images.ts", import.meta.url), lines.join("\n"));
console.log(`done: ${all.length} photos`);
